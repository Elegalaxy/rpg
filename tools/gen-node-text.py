"""Generate src/content/webs/nodeText.ts from the skill-web sections of doc/GAME_DESIGN.md."""
import json, re, sys

doc = open('doc/GAME_DESIGN.md', encoding='utf8').read().split('\n')

def kebab(name):
    s = name.lower().replace("'", '').replace('\u2019', '')
    s = re.sub(r'[^a-z0-9]+', '-', s)
    return s.strip('-')

out = {}
mode = None  # ('class', id) or ('race', id)
cluster = None
pending = None
for i, line in enumerate(doc):
    m = re.match(r'^### Provisional (\w+) web', line)
    if m:
        mode = ('class', m.group(1).lower()); pending = None; continue
    m = re.match(r'^#### (\w+) branch', line)
    if m and mode is not None or re.match(r'^### Provisional racial branches', line):
        pass
    m = re.match(r'^#### (Human|Elf|Beastfolk|Undead) branch', line)
    if m:
        mode = ('race', m.group(1).lower()); pending = None; continue
    if line.startswith('### ') and not re.match(r'^### Provisional', line):
        if not line.startswith('### Provisional racial'):
            mode = None; pending = None
    if mode is None:
        continue
    m = re.match(r'^(\d)\. (.+?)(?:, (?:major keystone|capstone))?: (.*)$', line)
    if m:
        name, text = m.group(2), m.group(3)
        nid = f'{mode[1]}-{kebab(name)}'
        out[nid] = text
        pending = nid
        continue
    if pending and re.match(r'^   - ', line):
        out[pending] += '\n' + line.strip()[2:]
        continue
    if line.strip() == '' or line.startswith('#'):
        pass
# Convergence recipes
rec = []
for i, line in enumerate(doc):
    if line.startswith('Initial invocation recipes'):
        j = i + 2
        while j < len(doc) and doc[j].startswith('- '):
            rec.append(doc[j][2:]); j += 1
if rec:
    out['mage-elemental-convergence'] += '\nRecipes:\n' + '\n'.join(rec)

body = 'export const nodeText: { readonly [nodeId: string]: string } = ' + json.dumps(out, indent=2, ensure_ascii=False) + '\n'
header = "// Generated by tools/gen-node-text.py from doc/GAME_DESIGN.md. Edit the design doc, then run the script again.\n"
open('src/content/webs/nodeText.ts', 'w', encoding='utf8').write(header + body)
print(len(out), 'nodes', file=sys.stderr)
